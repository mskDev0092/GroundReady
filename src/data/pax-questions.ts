import type { AcademyQuestion, PaxModuleCode } from "@/lib/types";

/**
 * AHM 1110 passenger-handling micro-drills.
 *
 * Two new questions per module give every pathway step a dedicated practice
 * set. Existing Knowledge Gym questions are mapped to the same modules in
 * `pax.ts`, so learners also revisit rules they have already met elsewhere.
 *
 * Training material only — always follow the current operator manual, carrier
 * rules and local station SOP.
 */

function pax(
  id: string,
  paxModule: PaxModuleCode,
  track: AcademyQuestion["track"],
  topic: string,
  difficulty: 1 | 2 | 3,
  question: string,
  options: [string, string, string, string],
  answer: number,
  explanation: string,
  reference: string,
  scenarioId?: string,
): AcademyQuestion {
  return {
    id,
    track,
    topic,
    difficulty,
    question,
    options,
    answer,
    explanation,
    reference,
    paxModule,
    ...(scenarioId ? { scenarioId } : {}),
  };
}

